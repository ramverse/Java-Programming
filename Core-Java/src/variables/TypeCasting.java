package variables;

public class TypeCasting {
    public static void main(){
        int marks=90;
        double percentage=marks;

        // with the help of typecasting int is converted in to double
        System.out.println(percentage);

        double pi=3.14;
        int value=(int) pi;

        //with the help of typecasting the value of pi that is double is converted into int
         System.out.println(value);

    }

}
