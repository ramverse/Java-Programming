package operators;

public class relationaloperators {

    public static void main(){

        int marks=80;
        int expectedmarks=100;

        System.out.println(marks>expectedmarks);
        System.out.println(marks>=expectedmarks);
        System.out.println(marks<expectedmarks);
        System.out.println(marks<=expectedmarks);
        System.out.println(marks==expectedmarks);
        System.out.println(marks!=expectedmarks);




    }

}
